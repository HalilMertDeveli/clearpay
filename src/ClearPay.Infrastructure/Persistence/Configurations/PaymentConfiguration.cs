using ClearPay.Domain.Ledger;
using ClearPay.Domain.Payments;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace ClearPay.Infrastructure.Persistence.Configurations;

internal sealed class PaymentConfiguration : IEntityTypeConfiguration<Payment>
{
    public const string MerchantOrderUnique = "UX_Payment_MerchantId_MerchantOrderId";

    public const string StatusCreated = "IX_Payment_Status_CreatedAt";

    public void Configure(EntityTypeBuilder<Payment> builder)
    {
        builder.ToTable("Payment");
        builder.HasKey(p => p.Id);
        builder.Property(p => p.MerchantId).IsRequired().HasMaxLength(64);
        builder.Property(p => p.MerchantOrderId).IsRequired().HasMaxLength(64);
        builder.Property(p => p.Amount)
            .HasPrecision(LedgerSchema.AmountPrecision, LedgerSchema.AmountScale)
            .IsRequired();
        builder.Property(p => p.CapturedAmount)
            .HasPrecision(LedgerSchema.AmountPrecision, LedgerSchema.AmountScale)
            .IsRequired();
        builder.Property(p => p.RefundedAmount)
            .HasPrecision(LedgerSchema.AmountPrecision, LedgerSchema.AmountScale)
            .IsRequired();
        builder.Property(p => p.Currency).IsRequired().HasMaxLength(3).IsFixedLength();
        builder.Property(p => p.CardBin).IsRequired().HasMaxLength(6);
        builder.Property(p => p.CardLast4).IsRequired().HasMaxLength(4);
        builder.Property(p => p.Provider).IsRequired().HasMaxLength(32);
        builder.Property(p => p.Status).IsRequired();
        builder.Property(p => p.ThreeDsTransactionId).HasMaxLength(64);
        builder.Property(p => p.ProviderReference).HasMaxLength(64);
        builder.Property(p => p.FailureCode).HasMaxLength(32);
        builder.Property(p => p.FailureMessage).HasMaxLength(200);
        builder.Property(p => p.ReturnUrl).IsRequired().HasMaxLength(500);
        builder.Property(p => p.CreatedAt).IsRequired();
        builder.Property(p => p.UpdatedAt).IsRequired();

        // Optimistic concurrency: UPDATE ... WHERE Id = @id AND Version = @old. Works the same on
        // SQL Server and the SQLite test database (rowversion would not be generated by SQLite).
        builder.Property(p => p.Version).IsConcurrencyToken();
        builder.Ignore(p => p.RefundableAmount);

        builder.HasIndex(p => new { p.MerchantId, p.MerchantOrderId })
            .IsUnique()
            .HasDatabaseName(MerchantOrderUnique);
        builder.HasIndex(p => new { p.Status, p.CreatedAt })
            .HasDatabaseName(StatusCreated);

        builder.HasMany(p => p.Refunds)
            .WithOne()
            .HasForeignKey(r => r.PaymentId)
            .OnDelete(DeleteBehavior.Restrict)
            .HasConstraintName("FK_PaymentRefund_Payment");
    }
}

internal sealed class PaymentRefundConfiguration : IEntityTypeConfiguration<PaymentRefund>
{
    public void Configure(EntityTypeBuilder<PaymentRefund> builder)
    {
        builder.ToTable("PaymentRefund");
        builder.HasKey(r => r.Id);
        builder.Property(r => r.Amount)
            .HasPrecision(LedgerSchema.AmountPrecision, LedgerSchema.AmountScale)
            .IsRequired();
        builder.Property(r => r.Reason).HasMaxLength(200);
        builder.Property(r => r.Status).IsRequired();
        builder.Property(r => r.ProviderReference).HasMaxLength(64);
        builder.Property(r => r.FailureCode).HasMaxLength(32);
        builder.Property(r => r.CreatedAt).IsRequired();
        builder.HasIndex(r => r.PaymentId).HasDatabaseName("IX_PaymentRefund_PaymentId");
    }
}
